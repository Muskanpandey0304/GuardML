"""
GuardML FastAPI backend.

Exposes the agent loop, approval actions, and audit log via REST API.

Security model (Tasks 2, 3, 4):
  * Every route except /health requires `Authorization: Bearer <token>`.
  * Two roles: "user" (run agent, read own sessions) and "approver"
    (everything a user can do + approve/deny). Tokens come from env vars
    GUARDML_USERS and GUARDML_APPROVERS, format: "name:token,name2:token2".
  * `resolved_by` is ALWAYS the authenticated identity; client value is ignored.
  * Two-person rule: in production, you cannot approve your own request.
  * The environment (staging/production) is set by the server only
    (GUARDML_ENVIRONMENT). The client cannot choose it.
  * Session IDs are generated by the server; the client cannot pick one.
  * CORS is restricted to GUARDML_CORS_ORIGINS (never "*").
  * The app refuses to start if auth is misconfigured (fail closed).
"""
from __future__ import annotations

import hmac
import logging
import os
import re
import uuid
from dataclasses import dataclass
from typing import Any, Dict, List

from dotenv import load_dotenv

load_dotenv()

from fastapi import BackgroundTasks, Depends, FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from pydantic import BaseModel, ConfigDict, Field

try:
    from guardml.agent.loop import AgentLoop
    from guardml.audit.log import AuditLog
    from guardml.audit.replay import SessionReplay
    from guardml.toolguard.approval import ApprovalGate
    from guardml.reports.postmortem import PostMortemGenerator
except ImportError:
    from agent.loop import AgentLoop
    from audit.log import AuditLog
    from audit.replay import SessionReplay
    from toolguard.approval import ApprovalGate
    from reports.postmortem import PostMortemGenerator


logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Configuration (all validated at import time -> fail closed)
# ---------------------------------------------------------------------------

_VALID_ENVIRONMENTS = ('staging', 'production')
_NAME_RE = re.compile(r'^[A-Za-z0-9_.\-]{1,64}$')
_MIN_TOKEN_LEN = 32
_PLACEHOLDER_MARKERS = ('changeme', 'change-me', 'change_me', 'placeholder', 'your-token', 'your_token')


@dataclass(frozen=True)
class Identity:
    name: str
    role: str  # "user" | "approver"


def _load_server_environment() -> str:
    """The environment is decided by the server, never by the request."""
    env = os.getenv('GUARDML_ENVIRONMENT', 'staging').strip().lower()
    if env not in _VALID_ENVIRONMENTS:
        raise RuntimeError(
            f"GUARDML_ENVIRONMENT must be one of {_VALID_ENVIRONMENTS}, got {env!r}"
        )
    return env


def _load_auth() -> Dict[str, Identity]:
    """
    Parse GUARDML_USERS / GUARDML_APPROVERS into {token: Identity}.
    Raises RuntimeError on any problem. Token values are never put in messages.
    """
    tokens: Dict[str, Identity] = {}
    for env_name, role in (('GUARDML_USERS', 'user'), ('GUARDML_APPROVERS', 'approver')):
        raw = os.getenv(env_name, '').strip()
        for item in (p.strip() for p in raw.split(',')):
            if not item:
                continue
            name, sep, token = item.partition(':')
            name, token = name.strip(), token.strip()
            if not sep or not name or not token:
                raise RuntimeError(f"{env_name}: entries must look like 'name:token'")
            if not _NAME_RE.match(name):
                raise RuntimeError(f"{env_name}: invalid identity name {name!r}")
            if len(token) < _MIN_TOKEN_LEN:
                raise RuntimeError(
                    f"{env_name}: token for {name!r} is shorter than {_MIN_TOKEN_LEN} characters"
                )
            lowered = token.lower()
            if any(m in lowered for m in _PLACEHOLDER_MARKERS) or len(set(token)) < 10:
                raise RuntimeError(f"{env_name}: token for {name!r} looks like a placeholder")
            if token in tokens:
                raise RuntimeError(f"{env_name}: token for {name!r} duplicates another identity's token")
            tokens[token] = Identity(name=name, role=role)

    if not any(i.role == 'approver' for i in tokens.values()):
        raise RuntimeError(
            'No approvers configured. Set GUARDML_APPROVERS="name:token" '
            '(generate a token with: python -c "import secrets; print(secrets.token_urlsafe(32))")'
        )
    return tokens


def _load_cors_origins() -> List[str]:
    raw = os.getenv('GUARDML_CORS_ORIGINS', 'http://localhost:8501')
    origins = [o.strip().rstrip('/') for o in raw.split(',') if o.strip()]
    if not origins:
        raise RuntimeError('GUARDML_CORS_ORIGINS is empty')
    if any(o == '*' for o in origins):
        raise RuntimeError("GUARDML_CORS_ORIGINS must not contain '*'")
    return origins


SERVER_ENV: str = _load_server_environment()
_TOKENS: Dict[str, Identity] = _load_auth()
_CORS_ORIGINS: List[str] = _load_cors_origins()

# Interactive docs expose the full API surface; off unless explicitly enabled.
_docs_enabled = os.getenv('GUARDML_ENABLE_DOCS', '').strip() == '1'

app = FastAPI(
    title='GuardML API',
    version='1.1.0',
    docs_url='/docs' if _docs_enabled else None,
    redoc_url=None,
    openapi_url='/openapi.json' if _docs_enabled else None,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=_CORS_ORIGINS,
    allow_credentials=False,  # we use bearer tokens, not cookies
    allow_methods=['GET', 'POST'],
    allow_headers=['Authorization', 'Content-Type'],
)

audit = AuditLog()
approval_gate = ApprovalGate()
replay = SessionReplay()

# NOTE: in-memory only; lost on restart (persistence is a separate task).
_sessions: Dict[str, Any] = {}

logger.info(
    'GuardML API starting: environment=%s identities=%d cors_origins=%s',
    SERVER_ENV, len(_TOKENS), _CORS_ORIGINS,
)


# ---------------------------------------------------------------------------
# Authentication / authorization
# ---------------------------------------------------------------------------

_bearer = HTTPBearer(auto_error=False)


def get_identity(creds: HTTPAuthorizationCredentials | None = Depends(_bearer)) -> Identity:
    """Authenticate the caller from the Bearer token (constant-time compare)."""
    unauthorized = HTTPException(
        status_code=401,
        detail='Missing or invalid credentials',
        headers={'WWW-Authenticate': 'Bearer'},
    )
    if creds is None or not creds.credentials:
        raise unauthorized

    presented = creds.credentials.encode('utf-8')
    match: Identity | None = None
    # Compare against every token (no early exit) so timing doesn't leak which matched.
    for token, identity in _TOKENS.items():
        if hmac.compare_digest(presented, token.encode('utf-8')):
            match = identity
    if match is None:
        raise unauthorized
    return match


def require_approver(identity: Identity = Depends(get_identity)) -> Identity:
    if identity.role != 'approver':
        raise HTTPException(status_code=403, detail='Approver role required')
    return identity


def _assert_can_view(session_id: str, identity: Identity) -> None:
    """Approvers see any session; users only their own. 404 (not 403) avoids ID probing."""
    if identity.role == 'approver':
        return
    session = _sessions.get(session_id)
    if session is None or session.get('owner') != identity.name:
        raise HTTPException(status_code=404, detail='Session not found')


# ---------------------------------------------------------------------------
# Request models (unknown fields such as a client-sent `environment`,
# `session_id` or `resolved_by` are ignored, never trusted)
# ---------------------------------------------------------------------------

class RunRequest(BaseModel):
    model_config = ConfigDict(extra='ignore')
    message: str = Field(min_length=1, max_length=4000)


class ApprovalRequest(BaseModel):
    model_config = ConfigDict(extra='ignore')
    action: str = Field(max_length=16)


class PostMortemRequest(BaseModel):
    model_config = ConfigDict(extra='ignore')
    session_id: str = Field(min_length=1, max_length=64)
    diagnosis: str = Field(min_length=1, max_length=5000)
    title: str = Field(default='Model Performance Incident', max_length=200)


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------

@app.get('/me')
async def me(identity: Identity = Depends(get_identity)):
    """Who am I, and which environment is the server running in?"""
    return {'name': identity.name, 'role': identity.role, 'environment': SERVER_ENV}


@app.post('/run')
async def run_agent(
    request: RunRequest,
    background_tasks: BackgroundTasks,
    identity: Identity = Depends(get_identity),
):
    session_id = str(uuid.uuid4())  # server-generated; client cannot choose or overwrite
    session: Dict[str, Any] = {
        'status': 'running',
        'steps': [],
        'answer': None,
        'owner': identity.name,
        'environment': SERVER_ENV,
    }
    _sessions[session_id] = session

    def on_step(step):
        session['steps'].append(step)

    def run():
        try:
            loop = AgentLoop(environment=SERVER_ENV, on_step=on_step)
            result = loop.run(request.message, session_id=session_id)
            if not isinstance(result, dict):
                result = {
                    'answer': 'Operation completed.',
                    'tool_calls': len(session.get('steps', [])),
                    'complete': True,
                }
            session.update({
                'status': 'done',
                'answer': result.get('answer') or 'Completed.',
                'tool_calls': result.get('tool_calls', 0),
                'complete': result.get('complete', False),
            })
        except Exception:
            # Full details go to server logs only; clients get a generic message.
            logger.error('Agent error in session %s', session_id, exc_info=True)
            session['status'] = 'error'
            session['error'] = 'Agent failed. See server logs.'
            session['answer'] = f'⚠️ Error during execution (session {session_id}). See server logs.'

    background_tasks.add_task(run)
    return {'session_id': session_id, 'status': 'running'}


@app.get('/session/{session_id}')
async def get_session(session_id: str, identity: Identity = Depends(get_identity)):
    _assert_can_view(session_id, identity)
    if session_id not in _sessions:
        raise HTTPException(status_code=404, detail='Session not found')
    return _sessions[session_id]


@app.get('/approvals')
async def list_approvals(session_id: str = '', identity: Identity = Depends(get_identity)):
    pending = approval_gate.list_pending(session_id=session_id)
    if identity.role == 'approver':
        return pending
    # Regular users only see approvals that belong to their own sessions.
    return [
        a for a in pending
        if _sessions.get(a.get('session_id', ''), {}).get('owner') == identity.name
    ]


@app.post('/approvals/{approval_id}')
async def resolve_approval(
    approval_id: str,
    request: ApprovalRequest,
    identity: Identity = Depends(require_approver),
):
    if request.action not in ('approved', 'denied'):
        raise HTTPException(status_code=400, detail='action must be approved or denied')

    pending = next(
        (a for a in approval_gate.list_pending(session_id='') if a.get('id') == approval_id),
        None,
    )
    if pending is None:
        raise HTTPException(status_code=404, detail='No pending approval with that id')

    # Two-person rule: in production nobody approves their own request.
    # (Denying your own request is always allowed - it is the safe direction.)
    approval_env = pending.get('env') or SERVER_ENV
    if request.action == 'approved' and approval_env == 'production':
        requester = _sessions.get(pending.get('session_id', ''), {}).get('owner')
        if requester is None:
            raise HTTPException(
                status_code=403,
                detail='Cannot verify who requested this action; refusing production approval',
            )
        if requester == identity.name:
            raise HTTPException(
                status_code=403,
                detail='Two-person rule: you cannot approve your own production request',
            )

    try:
        # resolved_by comes from the authenticated identity, never from the client.
        approval_gate.resolve(approval_id, request.action, identity.name)
    except Exception:
        logger.warning('Approval resolve failed for %s', approval_id, exc_info=True)
        raise HTTPException(status_code=409, detail='Approval could not be resolved (expired or already resolved?)')

    logger.info('Approval %s -> %s by %s', approval_id, request.action, identity.name)
    return {'ok': True, 'approval_id': approval_id, 'action': request.action, 'resolved_by': identity.name}


@app.get('/audit')
async def get_audit_log(
    limit: int = Query(100, ge=1, le=1000),
    identity: Identity = Depends(get_identity),
):
    return audit.get_all(limit=limit)


@app.get('/audit/verify')
async def verify_audit_chain(identity: Identity = Depends(get_identity)):
    return audit.verify_chain()


@app.get('/audit/session/{session_id}')
async def get_audit_session(session_id: str, identity: Identity = Depends(get_identity)):
    _assert_can_view(session_id, identity)
    return audit.get_session(session_id)


@app.get('/replay/{session_id}')
async def replay_session(session_id: str, identity: Identity = Depends(get_identity)):
    _assert_can_view(session_id, identity)
    text = replay.replay_text(session_id)
    steps = list(replay.replay(session_id))
    return {'session_id': session_id, 'text': text, 'steps': steps}


@app.post('/postmortem')
async def generate_postmortem(request: PostMortemRequest, identity: Identity = Depends(get_identity)):
    _assert_can_view(request.session_id, identity)
    try:
        gen = PostMortemGenerator()
        report = gen.generate(
            session_id=request.session_id,
            diagnosis=request.diagnosis,
            title=request.title,
        )
        return {'report': report}
    except Exception:
        logger.error('Postmortem generation error', exc_info=True)
        raise HTTPException(status_code=500, detail='Post-mortem generation failed. See server logs.')


@app.get('/health')
async def health():
    """Unauthenticated liveness probe. Reveals nothing beyond service name."""
    return {'status': 'healthy', 'service': 'guardml-api'}
